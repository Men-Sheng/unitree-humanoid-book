#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""tune_probes.py — 把 bootstrap_probes.py 生成的英文式探针改成中文能命中的探针。

问题：`bootstrap_probes.py` 给每个概念生成的 include 是
    \\b(六个时间域s?)\\b
两处对中文稿子无效：
  1. `\\b` 是"单词边界"，CJK 没有词边界概念，Python 的 re 在中文两侧都不给 \\b；
  2. `s?` 是英文复数后缀，粘在中文词后面只会让模式更挑不上。
结果就是 claim-index 建出来 0 concept / 0 site——**一个看起来跑成功的空门禁**。

本脚本产 `bible/concept-probes-tuned.yaml`（skill 明说这个文件优先且不被覆盖），
规则：
  · 去掉 \\b 与 s?；
  · include = 概念名本身，外加名字里出现的 ASCII 词（如 FOC、MTPA、EtherCAT、i_q）；
  · 名字太长的（>14 字，多半是一句论断）额外给一个"前 8 字"的短形，
    并把 exclude 留空由人补——短形有误报风险，所以 tuned: true 之外还打 review: true；
  · home / case_sensitive 原样继承。

用法：python -X utf8 tools/tune_probes.py [--stats]
"""
import io
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "bible", "concept-probes.yaml")
DST = os.path.join(ROOT, "bible", "concept-probes-tuned.yaml")


def ascii_tokens(s):
    return [t for t in re.findall(r"[A-Za-z][A-Za-z0-9_./·-]{1,}", s) if len(t) >= 2]


def core(s):
    """从 include 里取回概念名（bootstrap 的格式是 \\b(名字s?)\\b）。"""
    m = re.search(r"\((.*)s\?\)", s or "")
    return m.group(1) if m else (s or "").strip("\\b() ")


def main():
    stats = "--stats" in sys.argv
    raw = io.open(SRC, encoding="utf-8").read()
    blocks = re.findall(
        r"- id: (.+)\n  name: (.+)\n  home: (.+)\n  include: (.+)\n", raw)
    out = ["# generated by tools/tune_probes.py — 中文可命中的探针，优先于 concept-probes.yaml",
           "# 规则见该脚本头注。review: true 的条目是短形匹配，有误报风险，需要人看一眼。",
           "schema_version: '1.0'", "probes:"]
    n_review = 0
    for pid, name, home, inc in blocks:
        nm = core(inc) or name.strip()
        pats = [nm] + ascii_tokens(nm)
        review = False
        if len(nm) > 14:
            pats.append(nm[:8])
            review = True
        seen, uniq = set(), []
        for p in pats:
            p = p.strip()
            if p and p not in seen:
                seen.add(p)
                uniq.append(p)
        pattern = "|".join(re.escape(p) for p in uniq)
        n_review += 1 if review else 0
        out.append("- id: %s" % pid.strip())
        out.append("  name: %s" % name.strip())
        out.append("  home: %s" % home.strip())
        out.append("  include: %s" % pattern)
        out.append("  exclude: ''")
        out.append("  homonym_guard: ''")
        out.append("  case_sensitive: false")
        out.append("  tuned: true")
        if review:
            out.append("  review: true")
    if stats:
        print("探针 %d 条，其中 %d 条带短形（review: true）" % (len(blocks), n_review))
        return 0
    io.open(DST, "w", encoding="utf-8").write(chr(10).join(out) + chr(10))
    print("写出 bible/concept-probes-tuned.yaml：%d 条探针，%d 条待复核短形"
          % (len(blocks), n_review))
    return 0


if __name__ == "__main__":
    sys.exit(main())
