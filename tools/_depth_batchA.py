import io

NL = chr(10)


def insert_after(u, prefix, block, must=True):
    p = 'drafts/unit-%s/draft.md' % u
    lines = io.open(p, encoding='utf-8').read().split(NL)
    idx = [k for k, l in enumerate(lines) if l.startswith(prefix)]
    if len(idx) != 1:
        print('!! u%s 锚点 %d 个：%s' % (u, len(idx), prefix[:28]))
        return False
    k = idx[0]
    lines[k + 1:k + 1] = ['', block.rstrip()]
    io.open(p, 'w', encoding='utf-8', newline=NL).write(NL.join(lines))
    print('ok u%s 在第 %d 行后插入（%d 字符）' % (u, k + 1, len(block)))
    return True


