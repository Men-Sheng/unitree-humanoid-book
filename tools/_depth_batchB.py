import io

NL = chr(10)


def insert_after(u, prefix, block):
    p = 'drafts/unit-%s/draft.md' % u
    lines = io.open(p, encoding='utf-8').read().split(NL)
    idx = [k for k, l in enumerate(lines) if l.startswith(prefix)]
    if not idx:                      # 退一步：整行包含也认（有的锚点不在行首）
        idx = [k for k, l in enumerate(lines) if prefix in l]
    if len(idx) != 1:
        print('!! u%s 锚点 %d 个：%s' % (u, len(idx), prefix[:30]))
        return
    lines[idx[0] + 1:idx[0] + 1] = ['', block.rstrip()]
    io.open(p, 'w', encoding='utf-8', newline=NL).write(NL.join(lines))
    print('ok u%s 第 %d 行后插入 %d 字符' % (u, idx[0] + 1, len(block)))


def replace(u, old, new):
    p = 'drafts/unit-%s/draft.md' % u
    t = io.open(p, encoding='utf-8').read()
    if t.count(old) != 1:
        print('!! u%s 替换锚点 count=%d：%s' % (u, t.count(old), old[:40]))
        return
    io.open(p, 'w', encoding='utf-8', newline=NL).write(t.replace(old, new))
    print('ok u%s 替换：%s' % (u, old[:34]))


