def cell(title, chs):
    key = None
    for k in PRI:
        if title.startswith(k) or k in title:
            key = k
            break
    words = PRI[key]
    parts, warn = [], []
    for c in chs:
        best = None
        for w in words:
            lines = [i for i, l in enumerate(TXT[c], 1) if w in l]
            if lines and (best is None or len(lines) > best[1]):
                best = (w, len(lines), lines[0])
        if best is None:
            warn.append('%s 无命中!' % c)
            continue
        if best[1] == 1:
            warn.append('%s:%s 仅 1 处' % (c, best[0]))
        parts.append('%s:%s@%d' % (c, best[0], best[2]))
    return ' / '.join(parts), warn


